#!/usr/bin/env bash
# Run only after DNS points the chosen hostname to this server and TCP 80/443
# is allowed by BOTH Oracle Cloud security rules and Ubuntu's firewall.
set -Eeuo pipefail
if [[ $# -ne 1 || ! "$1" =~ ^[a-zA-Z0-9]([a-zA-Z0-9.-]*[a-zA-Z0-9])?$ ]]; then
  echo "Usage: sudo bash setup_youtube_websub_https.sh youtube.example.com" >&2
  exit 2
fi
if [[ $EUID -ne 0 ]]; then echo "Please run with sudo." >&2; exit 2; fi
DOMAIN="$1"
ROOT=/home/ubuntu/chzzk-bot
test -f "$ROOT/.env" || { echo "Missing $ROOT/.env" >&2; exit 1; }
if grep -q '^YOUTUBE_WEBSUB_CALLBACK_URL=' "$ROOT/.env"; then
  echo 'WebSub callback already configured. Review settings manually before changing.' >&2
  exit 1
fi
if ! command -v caddy >/dev/null 2>&1; then
  apt-get update -qq
  apt-get install -y caddy
fi
# The public proxy forwards ONLY the webhook endpoint to local Python.
mkdir -p /etc/caddy
if [[ -f /etc/caddy/Caddyfile ]] && [[ -s /etc/caddy/Caddyfile ]] && ! grep -q '^# ABYSS_YOUTUBE_WEBSUB_AUTOGENERATED' /etc/caddy/Caddyfile; then
  echo "Existing Caddyfile detected. Refusing to overwrite it." >&2
  exit 1
fi
cat > /etc/caddy/Caddyfile <<EOF
# ABYSS_YOUTUBE_WEBSUB_AUTOGENERATED
$DOMAIN {
    @youtubeWebSub path /youtube/websub
    handle @youtubeWebSub {
        reverse_proxy 127.0.0.1:8765
    }
    respond 404
}
EOF
caddy validate --config /etc/caddy/Caddyfile
systemctl enable --now caddy
systemctl reload caddy
# Keep existing Discord settings and all other environment variables unchanged.
SECRET="$(python3 -c 'import secrets;print(secrets.token_urlsafe(48))')"
chmod 600 "$ROOT/.env"
printf '\nYOUTUBE_WEBSUB_CALLBACK_URL=https://%s/youtube/websub\nYOUTUBE_WEBSUB_SECRET=%s\nYOUTUBE_WEBSUB_PORT=8765\n' "$DOMAIN" "$SECRET" >> "$ROOT/.env"
systemctl restart chzzk-bot
systemctl is-active --quiet chzzk-bot
echo "WebSub configured at https://$DOMAIN/youtube/websub"
echo "Verify publicly accessible HTTPS and subscription validation in journalctl."
echo "Do NOT paste .env or the WebSub secret into a chat."
